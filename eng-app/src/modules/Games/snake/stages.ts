export interface Point {
  x: number;
  y: number;
}

/** 把地圖字串轉成牆壁座標 */
export const parseWalls = (map: readonly string[]): Point[] =>
  map.flatMap((row, y) => [...row].flatMap((ch, x) => (ch === '#' ? [{ x, y }] : [])));

/** 過關星等：愛心沒掉 3 星、掉 1 顆 2 星，其他 1 星 */
export const snakeStars = (livesLost: number): number =>
  livesLost === 0 ? 3 : livesLost === 1 ? 2 : 1;
